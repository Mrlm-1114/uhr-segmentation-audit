#!/usr/bin/env python3
"""Generate fig_teaser.tex (Fig. 1, key findings) with all numbers in one place.

Values correspond to the manuscript tables. Each value is annotated with its
number identifier for comparison against the released records.
"""
import math

V = {
    # (a) DeepGlobe test mIoU (%)
    "dg_reused": 63.50,      # eSevenDgLiteratureDeepLabPp (appears in pDgRepeatCount=9 of pAuditCount=10 papers)
    "dg_r50": 73.67,         # eSevenDgRFiveZeroSZeroFivePp (R50, S=1/2, val-selected R50 route)
    "dg_gain": "10.17",      # pDgCorrectedGain
    "dg_isd": 73.29,         # isdnetDgOfficialReproPp
    "dg_f2": 80.22,          # pDgFtwo (reported)
    # (b) observed speed ratios at matched accuracy (fastest measured generic route)
    "isd_dg": 2.16,          # pDgObservedRatio      (generic needs 2.16x ISDNet GPU-path latency)
    "isd_in": 3.27,          # pInriaObservedRatio
    "mag_dg": 8.2,           # eEightMagNetGenericTimeMultiplierObservedX (generic 8.2x faster)
    "fctl_in": 201.2,        # eEightFCtLGenericTimeMultiplierObservedX
    # (c) generic minus ISDNet (pp) under ISDNet's latency budget
    "dg_T": 0.80,            # officialBudgetDgFpThreeTwoDeltaPp
    "in_T": 0.71,            # officialBudgetInriaFpThreeTwoDeltaPp
    "dg_Tp": -3.25,          # budgetDgDeltaRFourPp
    "in_Tp": -21.58,         # budgetInriaDeltaRFourPp
    # URUR (dedicated URUR timing benchmark; ISDNet accuracy = published 45.8, our retrained model missed the 44.8 threshold)
    "isd_ur": 1 / 0.477535687517588,  # 1/ururObservedRatioReported: fastest generic route reaching 45.8 (B5 S1/8, 91.18 ms) vs ISDNet GPU path 190.94 ms -> generic 2.09x faster
    "ur_T": 2.712961768725151,        # ururOfficialBudgetDeltaReported
    "ur_Tp": 2.712961768725151,       # ururGpuBudgetDeltaReported
}

W, H = 7.16, 1.98
out = []
P = out.append

def fmt(v, nd=2):
    s = f"{abs(v):.{nd}f}"
    return ("+" if v > 0 else "$-$") + s

# ------------------------------------------------------------------ preamble
P(r"""% Fig. 1 -- key findings (IEEE double-column width, 7.16 in). Generated by gen_teaser.py
\documentclass[tikz,border=0pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{textcomp}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usetikzlibrary{arrows.meta,calc}
\definecolor{ink}{HTML}{1E2A36}
\definecolor{muted}{HTML}{5D6B7A}
\definecolor{faint}{HTML}{A3AFBB}
\definecolor{navy}{HTML}{1F4E79}
\definecolor{stagefill}{HTML}{F1F5F9}
\definecolor{grid}{HTML}{FFFFFF}
\definecolor{axis}{HTML}{8796A5}
\definecolor{rfifty}{HTML}{2878AD}
\definecolor{bfive}{HTML}{419A61}
\definecolor{isdnet}{HTML}{C54A43}
\definecolor{magnet}{HTML}{8964AB}
\definecolor{neg}{HTML}{F8EAE8}
\newcommand{\fs}{\fontsize{8}{9.4}\selectfont}
\newcommand{\fsb}{\fontsize{8}{9.4}\selectfont\bfseries}
\newcommand{\ftitle}{\fontsize{8.6}{10}\selectfont\bfseries}
\begin{document}
\frenchspacing\hyphenpenalty=10000\exhyphenpenalty=10000
\begin{tikzpicture}[x=1in,y=1in,line join=round,line cap=round]""")
P(rf"\useasboundingbox (0,0) rectangle ({W},{H});")

def card(x0, w, title, subtitle):
    P(rf"\fill[stagefill, rounded corners=3pt] ({x0},0) rectangle ({x0+w},{H});")
    P(rf"\node[anchor=west, font=\ftitle, text=navy, inner sep=0pt] at ({x0+0.10},{H-0.15}) {{{title}}};")
    P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({x0+0.10},{H-0.31}) {{{subtitle}}};")

# markers -------------------------------------------------------------
def m_circle(x, y, c, hollow=False):
    if hollow:
        P(rf"\draw[{c}, line width=0.8pt, fill=stagefill] ({x:.4f},{y:.4f}) circle (2.5pt);")
    else:
        P(rf"\fill[stagefill] ({x:.4f},{y:.4f}) circle (3.4pt); \fill[{c}] ({x:.4f},{y:.4f}) circle (2.7pt);")
def m_tri(x, y, c, hollow=False):
    path = rf"({x:.4f},{y:.4f}) ++(90:3.4pt) -- ++(-120:5.9pt) -- ++(0:5.9pt) -- cycle"
    if hollow:
        P(rf"\draw[{c}, line width=0.8pt, fill=stagefill] {path};")
    else:
        P(rf"\fill[{c}] {path};")
def m_diamond(x, y, c, hollow=False):
    path = rf"({x:.4f},{y:.4f}) ++(0,3.3pt) -- ++(-2.8pt,-3.3pt) -- ++(2.8pt,-3.3pt) -- ++(2.8pt,3.3pt) -- cycle"
    if hollow:
        P(rf"\draw[{c}, line width=0.8pt, fill=stagefill] {path};")
    else:
        P(rf"\fill[{c}] {path};")

# ------------------------------------------------------------------ (a)
ax0, aw = 0.00, 2.16
card(ax0, aw, "(a) Generic baseline strength", "DeepGlobe test mIoU (\\%)")
lo, hi = 60.0, 82.0
cx0, cx1 = ax0 + 0.66, ax0 + aw - 0.16
X = lambda v: cx0 + (v - lo) / (hi - lo) * (cx1 - cx0)
ytop, ybot = 1.55, 0.44
for t in (60, 65, 70, 75, 80):
    P(rf"\draw[grid, line width=0.7pt] ({X(t):.4f},{ybot}) -- ({X(t):.4f},{ytop});")
    P(rf"\node[font=\fs, text=muted, inner sep=0pt] at ({X(t):.4f},{ybot-0.11}) {{{t}}};")
yg, yu = 1.20, 0.74
P(rf"\node[anchor=west, font=\fsb, text=ink, inner sep=0pt] at ({ax0+0.10},{yg}) {{Generic}};")
P(rf"\node[anchor=west, font=\fsb, text=ink, inner sep=0pt] at ({ax0+0.10},{yu}) {{UHR}};")
xr, xg = X(V["dg_reused"]), X(V["dg_r50"])
xi, xf = X(V["dg_isd"]), X(V["dg_f2"])
# gain arrow
P(rf"\draw[-{{Stealth[length=3.6pt,width=3.4pt]}}, navy, line width=0.8pt] ({xr+0.055:.4f},{yg}) -- ({xg-0.065:.4f},{yg});")
P(rf"\node[anchor=south, font=\fsb, text=navy, inner sep=0pt] at ({(xr+xg)/2:.4f},{yg+0.065}) {{+{V['dg_gain']} pp}};")
m_circle(xr, yg, "muted", hollow=True)
m_circle(xg, yg, "rfifty")
m_tri(xi, yu, "isdnet")
m_diamond(xf, yu, "isdnet", hollow=True)
# value labels (below) and names (above for UHR row)
for x, v, y in ((xr, V["dg_reused"], yg), (xg, V["dg_r50"], yg), (xi, V["dg_isd"], yu), (xf, V["dg_f2"], yu)):
    P(rf"\node[anchor=north, font=\fs, text=ink, inner sep=0pt] at ({x:.4f},{y-0.075:.4f}) {{{v:.2f}}};")
P(rf"\node[anchor=south, font=\fs, text=muted, inner sep=0pt] at ({xi:.4f},{yu+0.075:.4f}) {{ISDNet}};")
P(rf"\node[anchor=south, font=\fs, text=muted, inner sep=0pt] at ({xf:.4f},{yu+0.075:.4f}) {{F2Net}};")
# legend
ly = 0.13
P(rf"\draw[muted, line width=0.8pt, fill=stagefill] ({ax0+0.16:.4f},{ly}) circle (2.5pt);")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({ax0+0.23:.4f},{ly}) {{reported in papers}};")
P(rf"\fill[muted] ({ax0+1.22:.4f},{ly}) circle (2.5pt);")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({ax0+1.29:.4f},{ly}) {{measured here}};")

# ------------------------------------------------------------------ (b)
bx0, bw = 2.28, 2.60
card(bx0, bw, "(b) Efficiency at matched accuracy", "speed vs. fastest generic route, same accuracy")
s = 0.50                                   # inches per decade
zc = bx0 + 1.62                            # x of ratio 1
L = lambda r: zc + math.log10(r) * s       # r > 1: UHR faster (right); r < 1: generic faster (left)
ytop_b, ybot_b = 1.55, 0.44
for dec, lab in ((-2, "100$\\times$"), (-1, "10$\\times$"), (0, "1"), (1, "10$\\times$")):
    xx = zc + dec * s
    P(rf"\draw[grid, line width=0.7pt] ({xx:.4f},{ybot_b}) -- ({xx:.4f},{ytop_b});")
    P(rf"\node[font=\fs, text=muted, inner sep=0pt] at ({xx:.4f},{ybot_b-0.11}) {{{lab}}};")
P(rf"\draw[axis, line width=0.7pt] ({zc:.4f},{ybot_b}) -- ({zc:.4f},{ytop_b});")
rowsb = [  # y, label, ratio (>1 UHR faster), color, value text
    (1.455, r"ISDNet$^{\ast}$\,$\cdot$\,DG", V["isd_dg"], "isdnet", f"{V['isd_dg']:.2f}$\\times$"),
    (1.255, r"ISDNet$^{\ast}$\,$\cdot$\,Inria", V["isd_in"], "isdnet", f"{V['isd_in']:.2f}$\\times$"),
    (1.055, r"ISDNet$^{\ast\dagger}$\,$\cdot$\,URUR", 1 / V["isd_ur"], "isdnet", f"{V['isd_ur']:.2f}$\\times$"),
    (0.855, r"MagNet\,$\cdot$\,DG", 1 / V["mag_dg"], "magnet", f"{V['mag_dg']:.1f}$\\times$"),
    (0.655, r"FCtL\,$\cdot$\,Inria", 1 / V["fctl_in"], "magnet", f"{V['fctl_in']:.1f}$\\times$"),
]
hb = 0.05
for y, lab, r, c, vt in rowsb:
    xe = L(r)
    a, b = sorted((zc, xe))
    P(rf"\fill[{c}, rounded corners=0.8pt] ({a:.4f},{y-hb}) rectangle ({b:.4f},{y+hb});")
    if r > 1:   # bar to the right: value right of bar, label left of axis
        P(rf"\node[anchor=west, font=\fs, text=ink, inner sep=0pt] at ({xe+0.05:.4f},{y}) {{{vt}}};")
        P(rf"\node[anchor=east, font=\fs, text=ink, inner sep=0pt] at ({zc-0.06:.4f},{y}) {{{lab}}};")
    else:       # bar to the left: value left of bar, label right of axis
        P(rf"\node[anchor=east, font=\fs, text=ink, inner sep=0pt] at ({xe-0.05:.4f},{y}) {{{vt}}};")
        P(rf"\node[anchor=west, font=\fs, text=ink, inner sep=0pt] at ({zc+0.06:.4f},{y}) {{{lab}}};")
P(rf"\node[anchor=east, font=\fs, text=muted, inner sep=0pt] at ({zc-0.06:.4f},{ybot_b+0.065}) {{$\leftarrow$ generic faster}};")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({zc+0.06:.4f},{ybot_b+0.065}) {{UHR faster $\rightarrow$}};")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({bx0+0.10:.4f},{0.13}) {{$^{{\ast}}$GPU path; $^{{\dagger}}$published accuracy; log scale}};")

# ------------------------------------------------------------------ (c)
cx0c, cw = 5.00, 2.16
card(cx0c, cw, "(c) Timing scope", "generic $-$ ISDNet at equal latency (pp)")
vlo, vhi = -24.0, 12.0
xl, xr2 = cx0c + 0.54, cx0c + cw - 0.10
XC = lambda v: xl + (v - vlo) / (vhi - vlo) * (xr2 - xl)
ytop_c, ybot_c = 1.55, 0.44
x0c = XC(0)
# ISDNet-ahead region (negative) shading
P(rf"\fill[neg] ({xl:.4f},{ybot_c}) rectangle ({x0c:.4f},{ytop_c});")
for t, lab in ((-20, "$-$20"), (-10, "$-$10"), (0, "0"), (10, "10")):
    if t != 0:
        P(rf"\draw[grid, line width=0.7pt] ({XC(t):.4f},{ybot_c}) -- ({XC(t):.4f},{ytop_c});")
    P(rf"\node[font=\fs, text=muted, inner sep=0pt] at ({XC(t):.4f},{ybot_c-0.11}) {{{lab}}};")
P(rf"\draw[axis, line width=0.7pt] ({x0c:.4f},{ybot_c}) -- ({x0c:.4f},{ytop_c});")
P(rf"\node[anchor=east, font=\fs, text=isdnet!85!black, inner sep=0pt] at ({x0c-0.06:.4f},{ybot_c+0.065}) {{$\leftarrow$ ISDNet ahead}};")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt, align=left] at ({x0c+0.05:.4f},{ybot_c+0.115}) {{generic\\ahead $\rightarrow$}};")
rowsc = [  # y, label, official-path delta, GPU-path delta
    (1.330, "DG", V["dg_T"], V["dg_Tp"]),
    (1.035, "Inria", V["in_T"], V["in_Tp"]),
    (0.740, r"URUR$^{\dagger}$", V["ur_T"], V["ur_Tp"]),
]
for y, lab, vT, vTp in rowsc:
    P(rf"\node[anchor=west, font=\fsb, text=ink, inner sep=0pt] at ({cx0c+0.10:.4f},{y}) {{{lab}}};")
    xa, xb = XC(vT), XC(vTp)
    same = abs(vT - vTp) < 1e-6
    if not same:
        P(rf"\draw[-{{Stealth[length=3.6pt,width=3.4pt]}}, ink, line width=0.8pt] ({xa-0.045 if xb < xa else xa+0.045:.4f},{y}) -- ({xb+0.05 if xb < xa else xb-0.05:.4f},{y});")
    # official path: hollow ring; GPU path: filled dot
    P(rf"\draw[ink, line width=0.8pt, fill=stagefill] ({xa:.4f},{y}) circle ({3.6 if same else 2.5}pt);")
    P(rf"\fill[stagefill] ({xb:.4f},{y}) circle ({3.4 if not same else 2.1}pt); \fill[ink] ({xb:.4f},{y}) circle ({2.7 if not same else 1.9}pt);")
    if same:   # identical deltas: label sits right of the zero line
        P(rf"\node[anchor=south west, font=\fs, text=ink, inner sep=0pt] at ({xb-0.03:.4f},{y+0.08:.4f}) {{{fmt(vTp)}}};")
    else:
        P(rf"\node[anchor=west, font=\fs, text=ink, inner sep=0pt] at ({xa+0.07:.4f},{y}) {{{fmt(vT)}}};")
        anc, dx = ("south east", 0.04) if xb > XC(-8) else ("south west", -0.09)
        P(rf"\node[anchor={anc}, font=\fs, text=ink, inner sep=0pt] at ({xb+dx:.4f},{y+0.075:.4f}) {{{fmt(vTp)}}};")
# legend
ly = 0.13
P(rf"\draw[ink, line width=0.8pt, fill=stagefill] ({cx0c+0.16:.4f},{ly}) circle (2.5pt);")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({cx0c+0.23:.4f},{ly}) {{official path}};")
P(rf"\fill[ink] ({cx0c+1.06:.4f},{ly}) circle (2.5pt);")
P(rf"\node[anchor=west, font=\fs, text=muted, inner sep=0pt] at ({cx0c+1.13:.4f},{ly}) {{GPU path}};")

P(r"\end{tikzpicture}")
P(r"\end{document}")
open("fig_teaser.tex", "w").write("\n".join(out) + "\n")
print("written")
